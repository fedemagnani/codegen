//! The host crate: a generated downstream crate expanding the probed package's probe macros

/// Package name of the host crate probing `package`
pub fn package_name(package: &str) -> String {
    format!("codegen-host-{package}")
}

/// Crate name of the host crate, the stem of the assembly file rustc emits
pub fn crate_name(package: &str) -> String {
    package_name(package).replace('-', "_")
}

/// Name of the host crate's runner, the binary `measure` builds, unique per package in a shared target dir
pub fn runner_name(package: &str) -> String {
    format!("codegen-runner-{package}")
}

/// What the host crate depends on and expands
pub struct Spec<'a> {
    pub package: &'a str,
    /// Directory of the probed package's manifest
    pub package_dir: &'a str,
    /// Crate name of the probed package's library, the root its probe macros are exported at
    pub library: &'a str,
    /// Features to build the probed package with, the one enabling an optional `codegen` included
    pub features: &'a [String],
    pub default_features: bool,
    /// Where the probed package gets `codegen` from, as a TOML dependency source such as `path = ".."`
    pub codegen_source: &'a str,
    pub probes: &'a [String],
    /// Probes with an inputs function, which the runner measures
    pub measured: &'a [String],
}

/// `Cargo.toml` of the host crate, an empty `[workspace]` keeping it out of any enclosing workspace
pub fn manifest(spec: &Spec<'_>) -> String {
    let name = package_name(spec.package);
    let path = toml_string(spec.package_dir);
    let features: Vec<String> = spec
        .features
        .iter()
        .map(|feature| toml_string(feature))
        .collect();
    let features = features.join(", ");
    let default_features = spec.default_features;
    let dependency = toml_key(spec.package);
    let codegen_source = spec.codegen_source;
    format!(
        "# generated by cargo-codegen, rewritten on every run
[package]
name = {name}
version = \"0.0.0\"
edition = \"2024\"
publish = false

[lib]
path = \"lib.rs\"

# runs the inputs functions for `measure`; only `measure` builds it
[[bin]]
name = {runner}
path = \"main.rs\"

[dependencies]
{dependency} = {{ path = {path}, default-features = {default_features}, features = [{features}] }}
# the probed package's own `codegen-probe`, its `enabled` feature unified onto every crate using it
codegen-probe = {{ {codegen_source}, features = [\"enabled\"] }}

# as the listings are emitted, one codegen unit included, so the runner's build compiles the probes the same way
[profile.release.package.{name}]
debug = \"limited\"
codegen-units = 1

[workspace]
",
        name = toml_string(&name),
        runner = toml_string(&runner_name(spec.package)),
    )
}

/// `lib.rs` of the host crate, expanding each probe macro in a module of its name, so their helper items can't clash
pub fn library(spec: &Spec<'_>) -> String {
    let mut text = format!(
        "//! Generated by cargo-codegen: expands the probes of `{}` as a downstream crate\n",
        spec.package
    );
    for probes in spec.probes {
        let library = spec.library;
        text.push_str(&format!(
            "\nmod {probes} {{\n    {library}::{probes}!();\n}}\n"
        ));
    }
    text
}

/// `main.rs` of the host crate: the runner, handing every inputs function the library exports to `Measure`
pub fn runner(spec: &Spec<'_>) -> String {
    let mut text = format!(
        "//! Generated by cargo-codegen: measures the probes of `{}` on their inputs\n\n\
         // linked for the inputs functions the library exports\n\
         extern crate {};\n",
        spec.package,
        crate_name(spec.package)
    );
    if spec.measured.is_empty() {
        text.push_str("\nfn main() {}\n");
        return text;
    }
    text.push_str("\nunsafe extern \"Rust\" {\n");
    for probe in spec.measured {
        text.push_str(&format!(
            "    safe fn __codegen_inputs_{probe}(measure: &mut ::codegen::Measure);\n"
        ));
    }
    text.push_str(
        "}\n\nfn main() -> ::std::process::ExitCode {\n    ::codegen::Measure::__main(&[\n",
    );
    for probe in spec.measured {
        text.push_str(&format!("        __codegen_inputs_{probe},\n"));
    }
    text.push_str("    ])\n}\n");
    text
}

/// A TOML basic string
fn toml_string(text: &str) -> String {
    let escaped = text.replace('\\', "\\\\").replace('"', "\\\"");
    format!("\"{escaped}\"")
}

/// A TOML key, quoted unless bare
fn toml_key(text: &str) -> String {
    let is_bare = text
        .chars()
        .all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_');
    if is_bare {
        text.to_string()
    } else {
        toml_string(text)
    }
}

#[cfg(test)]
mod test {
    use super::*;

    fn spec<'a>(features: &'a [String], probes: &'a [String]) -> Spec<'a> {
        Spec {
            package: "my-crate",
            package_dir: "/work/my \"crate\"",
            library: "my_crate",
            features,
            default_features: false,
            codegen_source: "path = \"/work/codegen\"",
            probes,
            measured: &[],
        }
    }

    #[test]
    fn the_manifest_depends_on_the_package_with_its_features() {
        let features = ["fast".to_string(), "codegen".to_string()];
        let manifest = manifest(&spec(&features, &[]));
        let dependency = r#"my-crate = { path = "/work/my \"crate\"", default-features = false, features = ["fast", "codegen"] }"#;
        assert!(
            manifest.contains(r#"name = "codegen-host-my-crate""#),
            "{manifest}"
        );
        let codegen = r#"codegen-probe = { path = "/work/codegen", features = ["enabled"] }"#;
        assert!(manifest.contains(dependency), "{manifest}");
        assert!(manifest.contains(codegen), "{manifest}");
        assert!(manifest.trim_end().ends_with("[workspace]"), "{manifest}");
        // the runner's build compiles the host as the listings do, a single codegen unit
        let profile = "[profile.release.package.\"codegen-host-my-crate\"]\ndebug = \"limited\"\ncodegen-units = 1\n";
        assert!(manifest.contains(profile), "{manifest}");
    }

    #[test]
    fn the_library_expands_every_probe_macro_in_its_own_module() {
        let probes = ["fast_probes".to_string(), "slow_probes".to_string()];
        let library = library(&spec(&[], &probes));
        let fast = "mod fast_probes {\n    my_crate::fast_probes!();\n}\n";
        let slow = "mod slow_probes {\n    my_crate::slow_probes!();\n}\n";
        assert!(library.contains(fast), "{library}");
        assert!(library.contains(slow), "{library}");
    }

    #[test]
    fn the_runner_calls_the_inputs_of_every_measured_probe() {
        let measured = ["fast_get".to_string(), "slow_get".to_string()];
        let mut spec = spec(&[], &[]);
        spec.measured = &measured;
        let runner = runner(&spec);
        let manifest = manifest(&spec);
        assert!(
            runner.contains("extern crate codegen_host_my_crate;"),
            "{runner}"
        );
        let declared = "    safe fn __codegen_inputs_slow_get(measure: &mut ::codegen::Measure);\n";
        assert!(runner.contains(declared), "{runner}");
        assert!(
            runner.contains("        __codegen_inputs_fast_get,\n"),
            "{runner}"
        );
        assert!(
            manifest.contains("name = \"codegen-runner-my-crate\""),
            "{manifest}"
        );
    }

    #[test]
    fn without_inputs_the_runner_does_nothing() {
        let runner = runner(&spec(&[], &[]));
        assert!(runner.ends_with("\nfn main() {}\n"), "{runner}");
    }

    #[test]
    fn names_follow_the_package() {
        let package = package_name("my-crate");
        let krate = crate_name("my-crate");
        assert_eq!(package, "codegen-host-my-crate");
        assert_eq!(krate, "codegen_host_my_crate");
    }
}
